import 'package:freezed_annotation/freezed_annotation.dart';

part 'article_view_model.freezed.dart';
part 'article_view_model.g.dart';

@freezed
class ArticleViewModel with _$ArticleViewModel {
  const factory ArticleViewModel({
    required String id,
    required String articleId,
    String? userId,
    DateTime? viewedAt,
    String? referrer,
    String? deviceInfo,
  }) = _ArticleViewModel;

  factory ArticleViewModel.fromJson(Map<String, dynamic> json) =>
      _$ArticleViewModelFromJson(json);

  factory ArticleViewModel.fromSupabase(Map<String, dynamic> json) {
    return ArticleViewModel(
      id: json['id'] as String? ?? '',
      articleId: json['article_id'] as String? ?? '',
      userId: json['user_id'] as String?,
      viewedAt: json['viewed_at'] != null 
          ? DateTime.parse(json['viewed_at'] as String) 
          : null,
      referrer: json['referrer'] as String?,
      deviceInfo: json['device_info'] as String?,
    );
  }

  Map<String, dynamic> toSupabaseMap() {
    return {
      'id': id,
      'article_id': articleId,
      'user_id': userId,
      'viewed_at': viewedAt?.toIso8601String(),
      'referrer': referrer,
      'device_info': deviceInfo,
    };
  }
  
  /// Create a new view for tracking
  static ArticleViewModel create({
    required String articleId,
    String? userId,
    String? referrer,
    String? deviceInfo,
  }) {
    return ArticleViewModel(
      id: '', // Will be generated by Supabase
      articleId: articleId,
      userId: userId,
      viewedAt: DateTime.now(),
      referrer: referrer,
      deviceInfo: deviceInfo,
    );
  }
}
